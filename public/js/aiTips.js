/**
 * Module 4: AI Financial Tips UI Logic
 */

document.addEventListener('DOMContentLoaded', () => {
  const fetchBtn = document.getElementById('btn-fetch-ai-tips');
  const tipsContainer = document.getElementById('ai-tips-container');

  if (fetchBtn) {
    fetchBtn.addEventListener('click', async () => {
      const assessment = window.latestAssessment;
      if (!assessment) {
        window.appToast('Please run the Loan Eligibility Checker first to generate a profile for AI coaching.', 'info');
        window.switchToTab('tab-loan-checker');
        return;
      }

      const originalText = fetchBtn.textContent;
      fetchBtn.disabled = true;
      fetchBtn.textContent = 'Generating Financial Coaching...';

      try {
        const response = await window.apiClient.post('ai/tips', {
          profileSummary: {
            monthlyIncome: assessment.input.monthlyIncome,
            requestedLoanAmount: assessment.input.requestedLoanAmount,
            maxEligibleAmount: assessment.maxEligibleAmount,
            creditScore: assessment.input.creditScore,
            foir: assessment.foir,
            dti: assessment.dti,
            status: assessment.status,
            riskTier: assessment.riskTier
          }
        });

        if (response.success) {
          renderAiTips(response.data);
          window.appToast('Financial coaching generated!', 'success');
        }
      } catch (err) {
        window.appToast(err.message || 'Failed to generate financial tips.', 'error');
      } finally {
        fetchBtn.disabled = false;
        fetchBtn.textContent = originalText;
      }
    });
  }

  function renderAiTips(data) {
    if (!tipsContainer) return;
    tipsContainer.style.display = 'block';

    const isClaude = data.source === 'claude';
    const badgeHtml = isClaude
      ? `<span class="ai-badge source-claude">✨ Powered by Anthropic Claude (${data.model || 'claude-3-5-sonnet'})</span>`
      : `<span class="ai-badge source-fallback">⚡ Demo Rule-Based Guidance (Offline Fallback)</span>`;

    tipsContainer.innerHTML = `
      <div class="card" style="margin-top: 16px;">
        <div style="display: flex; justify-content: space-between; align-items: flex-start; flex-wrap: wrap; gap: 8px;">
          <div>
            <h3 class="card-title" style="margin-bottom: 4px;">Personalized Financial Coaching</h3>
            <p style="font-size: 0.85rem; color: var(--color-text-muted);">Educational analysis based on your debt-to-income and credit profile</p>
          </div>
          ${badgeHtml}
        </div>

        ${!isClaude ? `
          <div style="background: var(--color-warning-bg); border-left: 3px solid var(--color-warning); padding: 10px 14px; font-size: 0.82rem; margin: 14px 0; border-radius: 4px;">
            <strong>Notice:</strong> These recommendations were generated by the local demo rule engine because Claude API is currently unconfigured or offline.
          </div>
        ` : ''}

        <div class="ai-executive-glass-card">
          <div class="exec-header">
            <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 2v4M12 18v4M4.93 4.93l2.83 2.83M16.24 16.24l2.83 2.83M2 12h4M18 12h4M4.93 19.07l2.83-2.83M16.24 7.76l2.83-2.83"/></svg>
            <h4 class="exec-title">Executive Strategic Assessment</h4>
          </div>
          <p class="exec-body">${data.summary}</p>
        </div>

        <div class="grid-2col" style="margin-top: 16px;">
          <div style="background: var(--color-bg-subtle); border: 1px solid var(--color-border); border-radius: var(--radius-md); padding: 14px;">
            <h4 style="font-size: 0.88rem; font-weight: 700; color: var(--color-success); margin-bottom: 8px;">
              ✓ Financial Strengths
            </h4>
            <ul style="padding-left: 18px; font-size: 0.84rem; line-height: 1.5;">
              ${(data.strengths || []).map((s) => `<li>${s}</li>`).join('')}
            </ul>
          </div>

          <div style="background: var(--color-bg-subtle); border: 1px solid var(--color-border); border-radius: var(--radius-md); padding: 14px;">
            <h4 style="font-size: 0.88rem; font-weight: 700; color: var(--color-danger); margin-bottom: 8px;">
              ⚠ Vulnerabilities & Risks
            </h4>
            <ul style="padding-left: 18px; font-size: 0.84rem; line-height: 1.5;">
              ${(data.risks || []).map((r) => `<li>${r}</li>`).join('')}
            </ul>
          </div>
        </div>

        <div style="margin-top: 20px;">
          <h4 style="font-size: 0.92rem; font-weight: 700; margin-bottom: 10px;">Actionable Educational Roadmap:</h4>
          <ol style="padding-left: 20px; font-size: 0.88rem; line-height: 1.6;">
            ${(data.recommendations || []).map((rec) => `<li style="margin-bottom: 6px;"><strong>${rec.title || 'Tip'}:</strong> ${rec.detail || rec}</li>`).join('')}
          </ol>
        </div>

        <div style="margin-top: 20px; padding-top: 12px; border-top: 1px solid var(--color-border); font-size: 0.78rem; color: var(--color-text-muted);">
          <em>${data.disclaimer || 'Educational demo only. Not financial or credit counseling.'}</em>
        </div>
      </div>
    `;

    tipsContainer.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }
});
